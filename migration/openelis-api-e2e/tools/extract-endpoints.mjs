// Extract the REST endpoint catalog + per-endpoint HTTP verb map (the
// "manipulation pattern") from the OpenELIS Java source so the parity suite can
// (a) drive reachability over every GET and (b) cross-check write endpoints live.
// Emits fixtures/endpoints.generated.ts.  Run from openelis-api-e2e/.
import fs from "node:fs";
import path from "node:path";

const SRC =
  process.env.OE_SRC ||
  "E:/workspace/migration/OpenELIS-Global-2-go/src/main/java";

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (e.name.endsWith(".java")) out.push(p);
  }
  return out;
}

function firstPath(argStr) {
  if (argStr == null) return null;
  const m = argStr.match(/"([^"]*)"/);
  return m ? m[1] : "";
}

const files = walk(SRC).filter(
  (f) =>
    /controller[\\/]rest[\\/]/.test(f) ||
    /MenuController\.java$/.test(f) ||
    /DisplayListController\.java$/.test(f) ||
    /RestElectronicOrdersController\.java$/.test(f) ||
    /ProviderRestController\.java$/.test(f),
);

const norm = (base, method) => {
  let m = method || "";
  let full;
  if (/^\/?(rest|provider|health|fhir)\//i.test(m)) full = m;
  else full = (base || "") + (m.startsWith("/") ? m : "/" + m);
  return full.replace(/\/{2,}/g, "/").replace(/^\//, "");
};

// path -> Set(verbs)
const methods = new Map();
const add = (full, verb) => {
  if (!/^(rest|Provider|provider|health|fhir)\//.test(full)) return;
  if (!methods.has(full)) methods.set(full, new Set());
  methods.get(full).add(verb);
};

const VERB_ANN = [
  ["GetMapping", "GET"],
  ["PostMapping", "POST"],
  ["PutMapping", "PUT"],
  ["DeleteMapping", "DELETE"],
  ["PatchMapping", "PATCH"],
];

for (const f of files) {
  const src = fs.readFileSync(f, "utf8");
  const head = src.split(/public\s+(final\s+)?class/)[0];
  const baseM = head.match(/@RequestMapping\s*\(([^)]*)\)/);
  const base = baseM ? firstPath(baseM[1]) : "";

  for (const [ann, verb] of VERB_ANN) {
    const re = new RegExp(`@${ann}\\s*(\\(([^)]*)\\))?`, "g");
    let mm;
    while ((mm = re.exec(src))) {
      // support value = { "/a", "/b" } arrays: pull every literal
      const arg = mm[2] ?? "";
      const lits = arg.match(/"([^"]*)"/g) || [""];
      for (const lit of lits) add(norm(base, lit.replace(/"/g, "")), verb);
    }
  }
  // @RequestMapping(method = RequestMethod.X)
  const rm = /@RequestMapping\s*\(([^)]*method\s*=\s*RequestMethod\.(\w+)[^)]*)\)/g;
  let r;
  while ((r = rm.exec(src))) add(norm(base, firstPath(r[1])), r[2]);
}

const all = [...methods.entries()]
  .map(([p, v]) => ({ path: p, methods: [...v].sort() }))
  .sort((a, b) => a.path.localeCompare(b.path));

const getParamless = all
  .filter((e) => e.methods.includes("GET") && !e.path.includes("{"))
  .map((e) => e.path);
const getParam = all
  .filter((e) => e.methods.includes("GET") && e.path.includes("{"))
  .map((e) => e.path);
const writes = all.filter((e) =>
  e.methods.some((m) => ["POST", "PUT", "DELETE", "PATCH"].includes(m)),
);

const out = `// AUTO-GENERATED by tools/extract-endpoints.mjs — do not edit by hand.
export const GET_ENDPOINTS: string[] = ${JSON.stringify(getParamless, null, 2)};

export const GET_ENDPOINTS_WITH_PARAMS: string[] = ${JSON.stringify(getParam, null, 2)};

// Full per-endpoint verb map (the "manipulation pattern").
export interface EndpointMethods { path: string; methods: string[]; }
export const ENDPOINT_METHODS: EndpointMethods[] = ${JSON.stringify(all, null, 2)};

// Write endpoints (state-changing) — every one must be CSRF-protected.
export const WRITE_ENDPOINTS: EndpointMethods[] = ${JSON.stringify(writes, null, 2)};
`;
fs.mkdirSync("fixtures", { recursive: true });
fs.writeFileSync("fixtures/endpoints.generated.ts", out);

// summary of manipulation patterns
const pat = (m) => {
  const s = new Set(m);
  const w = ["POST", "PUT", "DELETE", "PATCH"].filter((x) => s.has(x));
  if (w.length === 0) return "read-only (GET)";
  if (s.has("PUT") || s.has("DELETE") || s.has("PATCH"))
    return "RESTful CRUD (GET/POST/PUT/DELETE)";
  return "form read+write (GET/POST)";
};
const counts = {};
for (const e of all) counts[pat(e.methods)] = (counts[pat(e.methods)] || 0) + 1;
console.log(
  `endpoints=${all.length}  GET-paramless=${getParamless.length}  GET-param=${getParam.length}  write=${writes.length}`,
);
console.log("manipulation patterns:", JSON.stringify(counts, null, 2));

// human-readable catalog: endpoint -> verbs -> pattern
const rows = all
  .map((e) => `| \`${e.path}\` | ${e.methods.join(", ")} | ${pat(e.methods)} |`)
  .join("\n");
const md = `# OpenELIS REST endpoint catalog & manipulation patterns

Auto-generated from source by \`tools/extract-endpoints.mjs\`. **${all.length}** endpoints.

| pattern | count |
|---|---:|
${Object.entries(counts)
  .map(([k, v]) => `| ${k} | ${v} |`)
  .join("\n")}

> Live note: the API does **not** expose verbs via \`OPTIONS\`/\`Allow\` — any non-GET
> without a CSRF token returns **403** (CSRF is enforced; token is in \`GET /session\`
> \`.csrf\`). So the verb map below is the authoritative source of truth; live
> per-verb probing requires CSRF + real payloads (the mutating suite, which resets
> the DB).

| endpoint | verbs | manipulation pattern |
|---|---|---|
${rows}
`;
fs.writeFileSync("ENDPOINT-CATALOG.md", md);
console.log("wrote ENDPOINT-CATALOG.md");
